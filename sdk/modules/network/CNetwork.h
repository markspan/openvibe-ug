#pragma once

/**
* @file CNetwork.h
* @brief Declaration of the CNetwork class for managing network clients and servers.
* @details This file contains the declaration of the CNetwork class, which provides methods to create and manage clients and servers,
* as well as utility functions for address resolution and validation.
* The class is designed to be used in a networked environment where multiple clients and servers need to be managed.
* It supports both IPv4 and IPv6 addresses, as well as hostnames.
* @note This class is part of a larger networking library and is intended for internal use.
* @see CClient
* @see CServer
* @see NAL
* @see ClientServerCommon
* @author Florent LERAY
* @date 2025-10-04
*/

#include <string>
#include <memory> // Pour std::unique_ptr
#include <vector> // Pour std::vector

#include <NAL.h> // for addrinfo and freeaddrinfo
#include <NetworkExport.h> // Generated by cmake with generate_export_header

#ifdef _WIN32
#include <firewall.h> // To provide firewall rule addition if needed (Windows only)
#endif

/**
 * @brief Network namespace encapsulating network-related classes and functions.
 * @details This namespace contains classes and functions for managing network clients and servers,
 * including connection establishment, data transmission, and protocol handling.
 */
namespace Network
{
    class CClient;
    class CServer;

    class CNetworkPrivate;

    /**
     * @class CNetwork
     * @brief CNetwork is a class that provides network functionalities, allowing to create clients and servers,
     * resolve addresses, and manage network resources.
     * It encapsulates the network's private data and operations.
     * It provides methods to create and remove clients and servers, resolve addresses, and format resolved addresses.
     *
     * The class is designed to be used in a networked environment where clients and servers can communicate over the network.
     */
    class CNetwork
    {
    public:
        CNetwork();
        ~CNetwork();

        CClient* createClient();
        CServer* createServer();

        void removeClient(CClient* client);
        void removeServer(CServer* server);

        /**
         * @brief Holds human-readable information about a resolved network address.
         */
        using AddressDetails = struct
        {
            int family;             //!< AF_INET or AF_INET6
            std::string ip;         //!< IP address as a string
            uint16_t port;          //!< Port number
            std::string hostname;   //!< Canonical hostname, if available
        };

        /**
         * @brief Smart pointer type for managing addrinfo structures.
         * @see getaddrinfo, freeaddrinfo
         * @note The custom deleter ensures that freeaddrinfo is called to free the memory allocated by getaddrinfo.
         */
        using AddrInfoSmartPtr = std::unique_ptr<addrinfo, decltype(&freeaddrinfo)>; // We use a unique_ptr with a custom deleter to ensure that freeaddrinfo is called to free the memory allocated by getaddrinfo





        static bool splitAddressAndPort(const std::string& addressWithPort, std::string& outAddress, uint16_t& outPort);

        static AddrInfoSmartPtr resolveAddress(const std::string& address, uint16_t port);
        static std::vector<AddressDetails> formatResolvedAddresses(const AddrInfoSmartPtr& resolvedAddresses);
        static bool resolvedAndFormat(const std::string& address, uint16_t port, AddrInfoSmartPtr& resolvedAddresses, std::vector<AddressDetails>& formattedAddresses);
        static bool resolvedAndFormat(const std::string& address, AddrInfoSmartPtr& resolvedAddresses, std::vector<AddressDetails>& formattedAddresses);

    private:
        // Disable copy constructor and assignment operator
        CNetwork(const CNetwork&) = delete;
        CNetwork& operator=(const CNetwork&) = delete;

        static bool isIpv4Address(const std::string& address);
        static bool isIpv6Address(const std::string& address);
        static bool isHostname(const std::string& address);
        static bool portExtract(std::string& portStr, uint16_t& outPort);

        static bool nameAndPortSplitter(const std::string& addressWithPort, std::string& outAddress, std::string& portStr);
        static bool IPv4OrHostnameSplitter(const std::string& addressWithPort, std::string& outAddress, std::string& portStr);
        static bool IPv6Splitter(const std::string& addressWithPort, std::string& outAddress, std::string& portStr);

    private:
        CNetworkPrivate* d;
    };
} // namespace Network
